import {
  PINE_MANIFEST_SCHEMA_VERSION,
  err,
  ok,
  type PineManifest,
  type Result,
  type StrategyDefinition,
} from "@arf/contracts";

/**
 * Approved Pine v6 template for the `ema_relation` trend-pullback family.
 * Tokens are replaced verbatim; the rendered output must pass `lintPine`
 * against the manifest produced by `manifestFromDefinition`.
 *
 * The same template is checked in at pine/boilerplate/arf_trend_pullback.template.pine
 * and a test keeps the two identical.
 */
export const TREND_PULLBACK_TEMPLATE = `//@version=6
// ARF-OS Strategy ID: {{STRATEGY_ID}}
// Strategy Version ID: {{STRATEGY_VERSION_ID}}
// SDL Hash: {{SDL_HASH}}
// Source Hash: generated after save
// Parent Version ID: {{PARENT_VERSION_ID}}
// Research Campaign ID: {{CAMPAIGN_ID}}
// Pine Version: 6
// Generated by: PINE_ENGINEER
// Human reviewed: false
strategy("{{TITLE}}", overlay = true, initial_capital = {{INITIAL_CAPITAL}}, currency = currency.{{CURRENCY}}, default_qty_type = {{QTY_TYPE}}, default_qty_value = {{QTY_VALUE}}, commission_type = {{COMMISSION_TYPE}}, commission_value = {{COMMISSION_VALUE}}, slippage = {{SLIPPAGE}}, pyramiding = 0, margin_long = {{MARGIN_LONG}}, margin_short = {{MARGIN_SHORT}}, process_orders_on_close = false, calc_on_every_tick = false, calc_on_order_fills = false)

// ---- Inputs ----------------------------------------------------------------
fast_length = input.int({{FAST_DEFAULT}}, "Fast EMA", minval = {{FAST_MIN}}, maxval = {{FAST_MAX}}, step = {{FAST_STEP}})
slow_length = input.int({{SLOW_DEFAULT}}, "Slow EMA", minval = {{SLOW_MIN}}, maxval = {{SLOW_MAX}}, step = {{SLOW_STEP}})
stop_atr = input.float({{STOP_DEFAULT}}, "Stop ATR multiple", minval = {{STOP_MIN}}, maxval = {{STOP_MAX}}, step = {{STOP_STEP}})
target_r = input.float({{TARGET_DEFAULT}}, "Target R multiple", minval = {{TARGET_MIN}}, maxval = {{TARGET_MAX}}, step = {{TARGET_STEP}})
start_date = input.time(timestamp("2020-01-01T00:00:00Z"), "Segment start")
end_date = input.time(timestamp("2099-01-01T00:00:00Z"), "Segment end")
deployment_id = input.string("unassigned", "ARF deployment id")

// ---- Data requests (confirmed higher-timeframe value) -----------------------
htf_close = request.security(syminfo.tickerid, "240", close[1], lookahead = barmerge.lookahead_on)

// ---- Indicators --------------------------------------------------------------
fast = ta.ema(close, fast_length)
slow = ta.ema(close, slow_length)
atr = ta.atr(14)

// ---- Regime, session and segment filters ------------------------------------
in_window = time >= start_date and time < end_date
in_session = not na(time(timeframe.period, "{{SESSION}}", "{{TIMEZONE}}"))
trend_fast_above_slow = fast > slow and close > htf_close
trend_fast_below_slow = fast < slow and close < htf_close
pullback_recovery = low < fast and close > fast
pullback_rejection = high > fast and close < fast
flat = strategy.position_size == 0

// ---- Entry conditions (closed bars only) ------------------------------------
long_signal = {{LONG_ENABLED}} and barstate.isconfirmed and in_window and in_session and flat and trend_fast_above_slow and pullback_recovery
short_signal = {{SHORT_ENABLED}} and barstate.isconfirmed and in_window and in_session and flat and trend_fast_below_slow and pullback_rejection

// ---- Alerts --------------------------------------------------------------------
alert_payload(string event_type, string order_id, float stop_price, float target_price) =>
    '{"schema":"arf.signal.v1","deploymentId":"' + deployment_id + '","strategyVersionId":"{{STRATEGY_VERSION_ID}}","eventId":"' + order_id + '-' + str.tostring(time) + '","eventType":"' + event_type + '","orderId":"' + order_id + '","symbol":"' + syminfo.prefix + ':' + syminfo.ticker + '","timeframe":"' + timeframe.period + '","barTime":"' + str.format_time(time, "yyyy-MM-dd'T'HH:mm:ss'Z'", "UTC") + '","sentAt":"' + str.format_time(timenow, "yyyy-MM-dd'T'HH:mm:ss'Z'", "UTC") + '","price":' + str.tostring(close) + ',"quantityModel":"{{QUANTITY_MODEL}}","stopPrice":' + str.tostring(stop_price) + ',"targetPrice":' + str.tostring(target_price) + '}'

// ---- Orders: one stop and one target, market entry on the next bar ----------
if long_signal
    long_stop = close - stop_atr * atr
    long_target = close + target_r * stop_atr * atr
    strategy.entry("L", strategy.long, alert_message = alert_payload("ENTRY_LONG", "L", long_stop, long_target))
    strategy.exit("L-exit", from_entry = "L", stop = long_stop, limit = long_target)

if short_signal
    short_stop = close + stop_atr * atr
    short_target = close - target_r * stop_atr * atr
    strategy.entry("S", strategy.short, alert_message = alert_payload("ENTRY_SHORT", "S", short_stop, short_target))
    strategy.exit("S-exit", from_entry = "S", stop = short_stop, limit = short_target)

// ---- Diagnostics -----------------------------------------------------------------
plot(fast, "Fast EMA", color = color.teal)
plot(slow, "Slow EMA", color = color.orange)
`;

export type TemplateFailure = { code: "TEMPLATE_NOT_AVAILABLE" | "TEMPLATE_PARAMETER_MISSING"; detail: string };

const QTY_TYPE = {
  percent_of_equity: "strategy.percent_of_equity",
  fixed_quantity: "strategy.fixed",
  fixed_cash: "strategy.cash",
} as const;

const COMMISSION_TYPE = {
  percent: "strategy.commission.percent",
  cash_per_order: "strategy.commission.cash_per_order",
  cash_per_contract: "strategy.commission.cash_per_contract",
} as const;

export interface ManifestIdentity {
  strategyId: string;
  strategyVersionId: string;
  campaignId: string;
  parentVersionId: string | null;
  sdlHash: string;
  symbol: string;
  timeframe: string;
  initialCapital: number;
  currency: string;
}

/** Definition-to-manifest mapping. Every manifest property is derived from the SDL or version identity. */
export function manifestFromDefinition(sdl: StrategyDefinition, id: ManifestIdentity): PineManifest {
  const qtyValue =
    sdl.risk.sizingModel === "percent_of_equity"
      ? (sdl.risk.sizePercent ?? 0)
      : sdl.risk.sizingModel === "fixed_quantity"
        ? (sdl.risk.fixedQuantity ?? 0)
        : (sdl.risk.fixedCash ?? 0);
  const marginPct = Math.round((100 / sdl.risk.leverage) * 100) / 100;
  return {
    schemaVersion: PINE_MANIFEST_SCHEMA_VERSION,
    pineVersion: 6,
    strategyId: id.strategyId,
    strategyVersionId: id.strategyVersionId,
    campaignId: id.campaignId,
    parentVersionId: id.parentVersionId,
    sdlHash: id.sdlHash,
    title: `ARF ${sdl.strategy.name}`.slice(0, 120),
    symbol: id.symbol,
    timeframe: id.timeframe,
    properties: {
      initialCapital: id.initialCapital,
      currency: id.currency,
      defaultQtyType: QTY_TYPE[sdl.risk.sizingModel],
      defaultQtyValue: qtyValue,
      commissionType: COMMISSION_TYPE[sdl.costs.commissionType],
      commissionValue: sdl.costs.commissionValue,
      slippageTicks: sdl.costs.slippageTicks,
      pyramiding: 0,
      marginLongPct: marginPct,
      marginShortPct: marginPct,
      processOrdersOnClose: sdl.execution.processOnClose,
      calcOnEveryTick: sdl.execution.calcOnEveryTick,
      calcOnOrderFills: false,
    },
    inputs: sdl.parameters.map((p) =>
      p.type === "bool"
        ? { key: p.key, type: "bool" as const, default: p.default }
        : { key: p.key, type: p.type, default: p.default, min: p.min, max: p.max, step: p.step },
    ),
    dateWindow: { startInputKey: "start_date", endInputKey: "end_date" },
    alertSchema: "arf.signal.v1",
  };
}

const fmt = (n: number) => String(n);

/** Render the approved template. Only `ema_relation` trend definitions with the four standard parameters are supported. */
export function renderTrendPullbackTemplate(
  sdl: StrategyDefinition,
  manifest: PineManifest,
): Result<string, TemplateFailure> {
  const trend = sdl.signals.trend;
  if (typeof trend !== "object" || trend.type !== "ema_relation" || sdl.execution.processOnClose || sdl.execution.calcOnEveryTick) {
    return err({ code: "TEMPLATE_NOT_AVAILABLE", detail: "the approved template supports ema_relation trend definitions with default execution only" });
  }
  const param = (key: string) => manifest.inputs.find((i) => i.key === key);
  const tokens: Record<string, string> = {
    STRATEGY_ID: manifest.strategyId,
    STRATEGY_VERSION_ID: manifest.strategyVersionId,
    SDL_HASH: manifest.sdlHash,
    PARENT_VERSION_ID: manifest.parentVersionId ?? "none",
    CAMPAIGN_ID: manifest.campaignId,
    TITLE: manifest.title.replace(/"/g, "'"),
    INITIAL_CAPITAL: fmt(manifest.properties.initialCapital),
    CURRENCY: manifest.properties.currency,
    QTY_TYPE: manifest.properties.defaultQtyType,
    QTY_VALUE: fmt(manifest.properties.defaultQtyValue),
    COMMISSION_TYPE: manifest.properties.commissionType,
    COMMISSION_VALUE: fmt(manifest.properties.commissionValue),
    SLIPPAGE: fmt(manifest.properties.slippageTicks),
    MARGIN_LONG: fmt(manifest.properties.marginLongPct),
    MARGIN_SHORT: fmt(manifest.properties.marginShortPct),
    SESSION: sdl.market.session,
    TIMEZONE: sdl.market.timezone,
    LONG_ENABLED: String(sdl.strategy.directions.includes("long")),
    SHORT_ENABLED: String(sdl.strategy.directions.includes("short")),
    QUANTITY_MODEL: sdl.risk.sizingModel,
  };
  const names: [string, string][] = [
    ["FAST", "fast_length"],
    ["SLOW", "slow_length"],
    ["STOP", "stop_atr"],
    ["TARGET", "target_r"],
  ];
  for (const [prefix, key] of names) {
    const p = param(key);
    if (!p || p.type === "bool" || p.min === undefined || p.max === undefined || p.step === undefined || typeof p.default !== "number") {
      return err({ code: "TEMPLATE_PARAMETER_MISSING", detail: `template requires numeric parameter ${key}` });
    }
    const asLiteral = (n: number) => (p.type === "float" && Number.isInteger(n) ? n.toFixed(1) : fmt(n));
    tokens[`${prefix}_DEFAULT`] = asLiteral(p.default);
    tokens[`${prefix}_MIN`] = asLiteral(p.min);
    tokens[`${prefix}_MAX`] = asLiteral(p.max);
    tokens[`${prefix}_STEP`] = fmt(p.step);
  }
  const rendered = TREND_PULLBACK_TEMPLATE.replace(/\{\{([A-Z_]+)\}\}/g, (_m, name: string) => {
    const value = tokens[name];
    if (value === undefined) throw new Error(`template token ${name} has no value`);
    return value;
  });
  return ok(rendered);
}
